@handler("social_rules_materialize")
def rules_materialize(ctx: JobCtx):
    """Daily backstop (and on-demand): extend every enabled rule's schedule to its horizon."""
    out = {}
    with ctx.session() as db:
        q = select(sm.SocialRule).where(sm.SocialRule.enabled)
        if ctx.payload.get("rule_id"):
            q = q.where(sm.SocialRule.id == uuid.UUID(ctx.payload["rule_id"]))
        for r in db.scalars(q):
            out[str(r.id)] = soc.materialize(db, r)["created"]
    return {"created": out}


