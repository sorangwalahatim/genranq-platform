def _generation_prompt(db, item: m.ContentItem, batch: sm.ContentBatch) -> str:
    prof = db.get(mm.ProjectProfile, item.project_id)
    data = (prof.data if prof else {}) or {}
    project = db.get(m.Project, item.project_id)
    ch = item.channel or batch.channel or "social"
    limit = soc.MAX_LEN.get(ch)
    ctx_lines = [f"{k.replace('_', ' ')}: {v}" for k, v in data.items() if v and k in
                 ("brand", "industry", "product", "audience", "location", "usp", "tone", "website")]
    existing = soc.item_body(db, item)
    return "\n".join([
        f"Write one {soc.CHANNEL_LABEL.get(ch, ch)} post for the brand '{data.get('brand') or project.name}'.",
        f"Topic / brief: {item.title or existing}",
        *(["Business context:"] + ctx_lines if ctx_lines else []),
        *([f"Existing draft to improve: {existing}"] if existing and existing != item.title else []),
        *([f"Extra instructions: {batch.instructions}"] if batch.instructions else []),
        f"Hard limit: {limit} characters including hashtags." if limit else "",
        "Return only the post text — no preamble, no quotes, no explanation.",
    ])


@handler("social_generate")
def generate(ctx: JobCtx):
    with ctx.session() as db:
        bi = db.get(sm.ContentBatchItem, uuid.UUID(ctx.payload["batch_item_id"]))
        if not bi:
            return {"status": "skipped"}
        item = db.get(m.ContentItem, bi.content_item_id)
        batch = db.get(sm.ContentBatch, bi.batch_id)
        if item.state != "draft":
            bi.gen_status, bi.gen_error = "skipped", f"Item is already '{item.state}'"
            return {"status": "skipped", "state": item.state}
        try:
            text, meta = agents.llm(db, ctx.org_id, _generation_prompt(db, item, batch), max_tokens=700)
        except agents.NoAI as e:
            bi.gen_status, bi.gen_error = "not_connected", f"NOT CONNECTED: {e}. The item stays a draft."
            return {"status": "not_connected"}
        text = (text or "").strip().strip('"').strip()
        lim = soc.MAX_LEN.get(item.channel or batch.channel or "")
        if not text:
            bi.gen_status, bi.gen_error = "failed", "The AI provider returned no text"
            return {"status": "failed"}
        if lim and len(text) > lim:
            text = text[:lim].rsplit(" ", 1)[0]
        try:  # the AI group's version helper keeps its version metadata in step
            from .ai_content import add_version
        except ImportError:
            add_version = None
        if add_version:
            ver = add_version(db, item, text, origin="ai", model=meta.get("model"), note=f"Content batch: {batch.name}").version
        else:
            ver = (db.scalar(select(func.max(m.ContentVersion.version)).where(m.ContentVersion.content_item_id == item.id)) or 0) + 1
            db.add(m.ContentVersion(organisation_id=ctx.org_id, content_item_id=item.id, version=ver, body=text))
        db.flush()
        try:
            soc.transition(db, None, item, "generated", f"Generated by AI ({meta.get('model', 'provider')})")
            bi.gen_status, bi.gen_error = "generated", None
        except soc.WorkflowUnavailable as e:
            bi.gen_status, bi.gen_error = "generated", f"Text saved as version {ver}; state not advanced: {e}"
        return {"status": "generated", "version": ver, "model": meta.get("model")}


@handler("social_report_run")
def report_run(ctx: JobCtx):
    with ctx.session() as db:
        rs = db.get(sm.ReportSchedule, uuid.UUID(ctx.payload["report_schedule_id"]))
        if not rs:
            raise PermanentError("Report schedule was deleted")
        if not rs.enabled and ctx.payload.get("triggered_by") == "schedule":
            return {"status": "skipped", "reason": "disabled"}
        job = db.get(m.Job, ctx.job_id)
        d = social_reports.run(db, ctx.org_id, rs, ctx.payload.get("triggered_by") or "manual", job.created_by if job else None)
        return {"delivery_id": str(d.id), "status": d.status, "files": len(d.files or [])}


